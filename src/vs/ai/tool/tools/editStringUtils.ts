export function countOccurrences(haystack: string, needle: string): number {
	if (!needle) { return 0; }
	let count = 0;
	let idx = haystack.indexOf(needle);
	while (idx !== -1) {
		count++;
		idx = haystack.indexOf(needle, idx + needle.length);
	}
	return count;
}
